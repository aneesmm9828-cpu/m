import React, { useState, useEffect } from 'react';
import {
  View,
  Text,
  StyleSheet,
  FlatList,
  TouchableOpacity,
  Image,
  TextInput,
  KeyboardAvoidingView,
  Platform,
  Alert,
  ActivityIndicator,
  Modal,
  ScrollView,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { Ionicons } from '@expo/vector-icons';
import { useRouter } from 'expo-router';
import { LinearGradient } from 'expo-linear-gradient';
import { Colors } from '../../constants/colors';
import { api } from '../../utils/api';
import { useAuthStore } from '../../store/authStore';

export default function AIAssistantScreen() {
  const router = useRouter();
  const { user } = useAuthStore();
  const [messages, setMessages] = useState([
    {
      id: '1',
      text: 'Hi! I\'m your AI Assistant 🤖\n\nI can help you with:\n• Generate photos & videos\n• Create reels ideas\n• Editing tips\n• Captions & content ideas\n\nWhat would you like to create today?',
      isAI: true,
    },
  ]);
  const [newMessage, setNewMessage] = useState('');
  const [loading, setLoading] = useState(false);
  const [showOptions, setShowOptions] = useState(false);
  const [aiProvider, setAiProvider] = useState('openai');
  const [generatedImage, setGeneratedImage] = useState(null);

  const sendMessage = async () => {
    if (!newMessage.trim()) return;

    const userMsg = {
      id: Date.now().toString(),
      text: newMessage,
      isAI: false,
    };

    setMessages([...messages, userMsg]);
    setNewMessage('');
    setLoading(true);

    try {
      const response = await api.post('/ai/chat', {
        message: newMessage,
        provider: aiProvider,
      });

      const aiMsg = {
        id: (Date.now() + 1).toString(),
        text: response.data.response,
        isAI: true,
      };

      setMessages((prev) => [...prev, aiMsg]);
    } catch (error) {
      console.error('AI chat error:', error);
      Alert.alert('Error', 'Failed to get AI response');
    } finally {
      setLoading(false);
    }
  };

  const generateImage = async (prompt: string) => {
    setLoading(true);
    try {
      const response = await api.post('/ai/image', {
        prompt,
        provider: aiProvider,
      });

      if (response.data.image) {
        setGeneratedImage(response.data.image);
        const aiMsg = {
          id: Date.now().toString(),
          text: '✅ Image generated! You can save it to your posts.',
          isAI: true,
          image: response.data.image,
        };
        setMessages((prev) => [...prev, aiMsg]);
      }
    } catch (error) {
      console.error('Image generation error:', error);
      Alert.alert('Error', 'Failed to generate image');
    } finally {
      setLoading(false);
    }
  };

  const quickActions = [
    {
      icon: 'image',
      title: 'Generate Photo',
      prompt: 'Create a beautiful landscape photo with mountains and sunset',
    },
    {
      icon: 'videocam',
      title: 'Reel Ideas',
      prompt: 'Give me 5 trending reel ideas for Instagram',
    },
    {
      icon: 'cut',
      title: 'Editing Tips',
      prompt: 'Give me professional video editing tips for reels',
    },
    {
      icon: 'text',
      title: 'Caption Ideas',
      prompt: 'Generate 5 catchy captions for my travel post',
    },
  ];

  const handleQuickAction = (action) => {
    if (action.title === 'Generate Photo') {
      Alert.prompt(
        'Generate Photo',
        'Describe the photo you want to create:',
        [
          { text: 'Cancel', style: 'cancel' },
          {
            text: 'Generate',
            onPress: (text) => {
              if (text) {
                const userMsg = {
                  id: Date.now().toString(),
                  text: `Generate: ${text}`,
                  isAI: false,
                };
                setMessages((prev) => [...prev, userMsg]);
                generateImage(text);
              }
            },
          },
        ],
        'plain-text',
        action.prompt
      );
    } else {
      setNewMessage(action.prompt);
    }
  };

  const saveGeneratedImage = async () => {
    if (!generatedImage) return;

    try {
      await api.post('/posts', {
        image: generatedImage,
        caption: 'Generated by AI ✨',
      });
      Alert.alert('Success', 'Image saved to your posts!');
      setGeneratedImage(null);
    } catch (error) {
      console.error('Save error:', error);
      Alert.alert('Error', 'Failed to save image');
    }
  };

  const renderMessage = ({ item }) => (
    <View style={[styles.messageContainer, item.isAI ? styles.aiMessage : styles.userMessage]}>
      {item.isAI && (
        <View style={styles.aiAvatar}>
          <LinearGradient
            colors={[Colors.primaryGradientStart, Colors.primaryGradientEnd]}
            style={styles.avatarGradient}
          >
            <Ionicons name="sparkles" size={20} color={Colors.background} />
          </LinearGradient>
        </View>
      )}
      <View style={[styles.messageBubble, item.isAI ? styles.aiBubble : styles.userBubble]}>
        {item.image && (
          <Image
            source={{ uri: `data:image/jpeg;base64,${item.image}` }}
            style={styles.generatedImage}
            resizeMode="cover"
          />
        )}
        <Text style={[styles.messageText, !item.isAI && styles.userMessageText]}>
          {item.text}
        </Text>
      </View>
    </View>
  );

  return (
    <SafeAreaView style={styles.container} edges={['top']}>
      {/* Header */}
      <View style={styles.header}>
        <TouchableOpacity onPress={() => router.back()} style={styles.backButton}>
          <Ionicons name="arrow-back" size={28} color={Colors.text} />
        </TouchableOpacity>
        <View style={styles.aiHeaderAvatar}>
          <LinearGradient
            colors={[Colors.primaryGradientStart, Colors.primaryGradientEnd]}
            style={styles.headerAvatarGradient}
          >
            <Ionicons name="sparkles" size={24} color={Colors.background} />
          </LinearGradient>
        </View>
        <View style={styles.headerInfo}>
          <Text style={styles.headerName}>AI Assistant</Text>
          <Text style={styles.headerStatus}>Always active</Text>
        </View>
        <TouchableOpacity onPress={() => setShowOptions(true)}>
          <Ionicons name="settings-outline" size={26} color={Colors.text} />
        </TouchableOpacity>
      </View>

      {/* Quick Actions */}
      <View style={styles.quickActionsContainer}>
        <ScrollView horizontal showsHorizontalScrollIndicator={false}>
          {quickActions.map((action, index) => (
            <TouchableOpacity
              key={index}
              style={styles.quickAction}
              onPress={() => handleQuickAction(action)}
            >
              <View style={styles.quickActionIcon}>
                <Ionicons name={action.icon} size={24} color={Colors.primary} />
              </View>
              <Text style={styles.quickActionText}>{action.title}</Text>
            </TouchableOpacity>
          ))}
        </ScrollView>
      </View>

      {/* Messages */}
      <FlatList
        data={messages}
        renderItem={renderMessage}
        keyExtractor={(item) => item.id}
        contentContainerStyle={styles.messagesList}
        inverted={false}
      />

      {loading && (
        <View style={styles.loadingContainer}>
          <ActivityIndicator size="small" color={Colors.primary} />
          <Text style={styles.loadingText}>AI is thinking...</Text>
        </View>
      )}

      {/* Generated Image Actions */}
      {generatedImage && (
        <View style={styles.imageActions}>
          <TouchableOpacity style={styles.imageActionButton} onPress={saveGeneratedImage}>
            <Ionicons name="save" size={20} color={Colors.primary} />
            <Text style={styles.imageActionText}>Save to Posts</Text>
          </TouchableOpacity>
          <TouchableOpacity
            style={styles.imageActionButton}
            onPress={() => setGeneratedImage(null)}
          >
            <Ionicons name="close" size={20} color={Colors.textSecondary} />
            <Text style={styles.imageActionText}>Dismiss</Text>
          </TouchableOpacity>
        </View>
      )}

      {/* Input */}
      <KeyboardAvoidingView
        behavior={Platform.OS === 'ios' ? 'padding' : 'height'}
        keyboardVerticalOffset={90}
      >
        <View style={styles.inputContainer}>
          <TextInput
            style={styles.input}
            placeholder="Ask AI anything..."
            placeholderTextColor={Colors.textSecondary}
            value={newMessage}
            onChangeText={setNewMessage}
            multiline
          />
          <TouchableOpacity onPress={sendMessage} disabled={loading || !newMessage.trim()}>
            <LinearGradient
              colors={[Colors.primaryGradientStart, Colors.primaryGradientEnd]}
              style={styles.sendButton}
            >
              <Ionicons name="send" size={20} color={Colors.background} />
            </LinearGradient>
          </TouchableOpacity>
        </View>
      </KeyboardAvoidingView>

      {/* Settings Modal */}
      <Modal visible={showOptions} transparent animationType="slide">
        <View style={styles.modalOverlay}>
          <View style={styles.modalContent}>
            <View style={styles.modalHeader}>
              <Text style={styles.modalTitle}>AI Provider</Text>
              <TouchableOpacity onPress={() => setShowOptions(false)}>
                <Ionicons name="close" size={28} color={Colors.text} />
              </TouchableOpacity>
            </View>

            <TouchableOpacity
              style={[
                styles.providerOption,
                aiProvider === 'openai' && styles.providerOptionActive,
              ]}
              onPress={() => {
                setAiProvider('openai');
                setShowOptions(false);
              }}
            >
              <Text style={styles.providerText}>OpenAI GPT-4 + DALL-E</Text>
              {aiProvider === 'openai' && (
                <Ionicons name="checkmark-circle" size={24} color={Colors.primary} />
              )}
            </TouchableOpacity>

            <TouchableOpacity
              style={[
                styles.providerOption,
                aiProvider === 'gemini' && styles.providerOptionActive,
              ]}
              onPress={() => {
                setAiProvider('gemini');
                setShowOptions(false);
              }}
            >
              <Text style={styles.providerText}>Google Gemini + Nano Banana</Text>
              {aiProvider === 'gemini' && (
                <Ionicons name="checkmark-circle" size={24} color={Colors.primary} />
              )}
            </TouchableOpacity>
          </View>
        </View>
      </Modal>
    </SafeAreaView>
  );
}

